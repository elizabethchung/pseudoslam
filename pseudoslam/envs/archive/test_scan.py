import numpy as np
import matplotlib.pyplot as plt

def plot_lidar_polar(lidar_data):
    """
    Plots LiDAR distance data on a polar plot.
    
    Args:
        lidar_data (np.ndarray): 1D array of distances, indices represent angles in degrees.
    """
    # Angles in radians for polar plot
    angles = np.deg2rad(np.arange(len(lidar_data)))
    
    # Make the plot circular by appending the first point to the end
    angles = np.append(angles, angles[0])
    distances = np.append(lidar_data, lidar_data[0])
    
    fig, ax = plt.subplots(subplot_kw={'projection': 'polar'})
    ax.plot(angles, distances, linestyle='-', marker='.')
    ax.fill(angles, distances, alpha=0.3)
    
    ax.set_theta_zero_location('N')  # 0 degrees at top (north)
    ax.set_theta_direction(-1)       # Degrees go clockwise
    
    ax.set_title("LiDAR Distance Polar Plot")
    plt.show()


